USE ROLE SYSADMIN;
USE WAREHOUSE FINAL_JURY_WH;
USE DATABASE HEALTHCARE_FINAL_JURY;
USE SCHEMA STAGING;

SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT ENCOUNTER_KEY) AS UNIQUE_ENCOUNTER_KEYS,
    COUNT_IF(SOURCE_KEY = 'UCI_DIABETES') AS UCI_ROWS,
    COUNT_IF(SOURCE_KEY = 'SPARCS_2023') AS SPARCS_2023_ROWS,
    COUNT_IF(SOURCE_KEY = 'SPARCS_2024') AS SPARCS_2024_ROWS,
    COUNT_IF(TRY_TO_BOOLEAN(READMISSION_LABEL_AVAILABLE)) AS LABEL_AVAILABLE_ROWS,
    COALESCE(COUNT_IF(TRY_TO_BOOLEAN(IS_SYNTHETIC)), 0) AS SYNTHETIC_ROWS
FROM MODELLED_RAW;
-- Expected: 4424257, 4424257, 101766, 2125754, 2196737, 101766, 0.

SELECT SOURCE_KEY, MODEL_ROLE, COUNT(*) AS RECORDS
FROM MODELLED_RAW
GROUP BY SOURCE_KEY, MODEL_ROLE
ORDER BY SOURCE_KEY, MODEL_ROLE;
-- UCI: train 59565, validation 19917, test 19861, excluded 2423.
-- SPARCS 2023 unlabeled train candidate: 2125754.
-- SPARCS 2024 unlabeled holdout candidate: 2196737.

SELECT READMISSION_LABEL, COUNT(*) AS RECORDS
FROM MODELLED_RAW
WHERE SOURCE_KEY = 'UCI_DIABETES'
GROUP BY READMISSION_LABEL
ORDER BY READMISSION_LABEL;
-- NO: 54864; >30: 35545; <30: 11357.

SELECT
    COALESCE(COUNT_IF(ENCOUNTER_KEY IS NULL OR SOURCE_KEY IS NULL OR SOURCE_ROW_ID IS NULL), 0)
        AS MISSING_SOURCE_IDENTIFIERS,
    COALESCE(COUNT_IF(SOURCE_KEY IN ('SPARCS_2023', 'SPARCS_2024') AND READMISSION_LABEL IS NOT NULL), 0)
        AS UNEXPECTED_SPARCS_READMISSION_LABELS,
    COALESCE(COUNT_IF(SOURCE_KEY IN ('SPARCS_2023', 'SPARCS_2024') AND PATIENT_KEY IS NOT NULL), 0)
        AS UNEXPECTED_SPARCS_PATIENT_LINKS,
    COALESCE(COUNT_IF(READMISSION_LABEL_AVAILABLE IS NULL OR TRY_TO_BOOLEAN(READMISSION_LABEL_AVAILABLE) IS NULL), 0)
        AS INVALID_LABEL_AVAILABILITY_FLAGS,
    COALESCE(COUNT_IF(IS_SYNTHETIC IS NULL OR TRY_TO_BOOLEAN(IS_SYNTHETIC) IS NULL), 0)
        AS INVALID_SYNTHETIC_FLAGS,
    COUNT_IF(SOURCE_KEY = 'UCI_DIABETES' AND UCI_A1CRESULT = 'None')
        AS UCI_HBA1C_NOT_PERFORMED,
    COUNT_IF(SOURCE_KEY = 'UCI_DIABETES' AND UCI_MAX_GLU_SERUM = 'None')
        AS UCI_GLUCOSE_NOT_PERFORMED
FROM MODELLED_RAW;
-- Expected: 0, 0, 0, 0, 0, 84748, 96420.
