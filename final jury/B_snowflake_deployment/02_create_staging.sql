-- Final jury step 2: preserve all source fields in a landing table.
USE ROLE SYSADMIN;
USE WAREHOUSE FINAL_JURY_WH;
USE DATABASE HEALTHCARE_FINAL_JURY;
CREATE SCHEMA IF NOT EXISTS HEALTHCARE_FINAL_JURY.STAGING;
USE SCHEMA STAGING;

CREATE FILE FORMAT IF NOT EXISTS MODELLED_CSV_FORMAT
    TYPE = CSV
    COMPRESSION = AUTO
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    ESCAPE_UNENCLOSED_FIELD = NONE
    EMPTY_FIELD_AS_NULL = TRUE
    NULL_IF = ('')
    TRIM_SPACE = FALSE
    ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE
    REPLACE_INVALID_CHARACTERS = FALSE
    ENCODING = 'UTF8';

-- Text landing preserves IDs, original categories, booleans, and None tokens.
-- Types and integrity rules are applied when populating DW tables.
CREATE TABLE IF NOT EXISTS MODELLED_RAW (
    ENCOUNTER_KEY VARCHAR,
    SOURCE_KEY VARCHAR,
    SOURCE_ROW_ID VARCHAR,
    PATIENT_KEY VARCHAR,
    PERIOD VARCHAR,
    DISCHARGE_YEAR VARCHAR,
    FACILITY_KEY VARCHAR,
    FACILITY_NAME VARCHAR,
    HOSPITAL_COUNTY VARCHAR,
    SERVICE_AREA VARCHAR,
    AGE_BAND_RAW VARCHAR,
    AGE_BAND_COMMON VARCHAR,
    GENDER VARCHAR,
    RACE_RAW VARCHAR,
    ETHNICITY_RAW VARCHAR,
    ADMISSION_TYPE_RAW VARCHAR,
    ADMISSION_TYPE_COMMON VARCHAR,
    DISPOSITION_RAW VARCHAR,
    DIAGNOSIS_SYSTEM VARCHAR,
    DIAGNOSIS_CODE VARCHAR,
    DIAGNOSIS_DESCRIPTION VARCHAR,
    LOS_RAW VARCHAR,
    LOS_DAYS_LOWER_BOUND VARCHAR,
    LOS_TOP_CODED VARCHAR,
    TOTAL_CHARGES_USD VARCHAR,
    TOTAL_COSTS_USD VARCHAR,
    SEVERITY_CODE VARCHAR,
    SEVERITY_DESCRIPTION VARCHAR,
    APR_DRG_CODE VARCHAR,
    PAYMENT_TYPE VARCHAR,
    READMISSION_LABEL VARCHAR,
    READMISSION_LABEL_AVAILABLE VARCHAR,
    DIABETES_COHORT_DEFINITION VARCHAR,
    IS_SYNTHETIC VARCHAR,
    UCI_NUM_LAB_PROCEDURES VARCHAR,
    UCI_NUM_PROCEDURES VARCHAR,
    UCI_NUM_MEDICATIONS VARCHAR,
    UCI_NUMBER_OUTPATIENT VARCHAR,
    UCI_NUMBER_EMERGENCY VARCHAR,
    UCI_NUMBER_INPATIENT VARCHAR,
    UCI_NUMBER_DIAGNOSES VARCHAR,
    UCI_INSULIN VARCHAR,
    UCI_CHANGE VARCHAR,
    UCI_DIABETESMED VARCHAR,
    UCI_A1CRESULT VARCHAR,
    UCI_MAX_GLU_SERUM VARCHAR,
    UCI_DIAG_2 VARCHAR,
    UCI_DIAG_3 VARCHAR,
    UCI_ADMISSION_SOURCE_ID VARCHAR,
    MODEL_ROLE VARCHAR,
    LABEL_ORIGIN VARCHAR
);

CREATE STAGE IF NOT EXISTS MODELLED_STAGE
    FILE_FORMAT = (FORMAT_NAME = 'HEALTHCARE_FINAL_JURY.STAGING.MODELLED_CSV_FORMAT');

-- Source-column order must match modelled.csv.
SELECT ORDINAL_POSITION, COLUMN_NAME, DATA_TYPE
FROM HEALTHCARE_FINAL_JURY.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'STAGING' AND TABLE_NAME = 'MODELLED_RAW'
ORDER BY ORDINAL_POSITION;

SHOW STAGES LIKE 'MODELLED_STAGE' IN SCHEMA HEALTHCARE_FINAL_JURY.STAGING;
DESCRIBE FILE FORMAT HEALTHCARE_FINAL_JURY.STAGING.MODELLED_CSV_FORMAT;

-- Final checkpoint: the result should be 51.
SELECT COUNT(*) AS STAGING_COLUMN_COUNT
FROM HEALTHCARE_FINAL_JURY.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'STAGING' AND TABLE_NAME = 'MODELLED_RAW';
