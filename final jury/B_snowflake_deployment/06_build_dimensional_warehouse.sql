SELECT ROW_NUMBER() OVER (ORDER BY SOURCE_KEY NULLS FIRST, ADMISSION_TYPE_RAW NULLS FIRST, ADMISSION_TYPE_COMMON NULLS FIRST, DISPOSITION_RAW NULLS FIRST, PAYMENT_TYPE NULLS FIRST, UCI_ADMISSION_SOURCE_ID NULLS FIRST) AS ADMISSION_ID, SOURCE_KEY, ADMISSION_TYPE_RAW, ADMISSION_TYPE_COMMON, DISPOSITION_RAW, PAYMENT_TYPE, UCI_ADMISSION_SOURCE_ID
FROM (SELECT DISTINCT SOURCE_KEY, ADMISSION_TYPE_RAW, ADMISSION_TYPE_COMMON, DISPOSITION_RAW, PAYMENT_TYPE, UCI_ADMISSION_SOURCE_ID FROM ETL_ENCOUNTER_TYPED)
