CREATE TABLE IF NOT EXISTS DIM_SOURCE (
    SOURCE_ID NUMBER(38,0) NOT NULL PRIMARY KEY,
    SOURCE_KEY VARCHAR,
    DIABETES_COHORT_DEFINITION VARCHAR
);

INSERT INTO DIM_SOURCE
SELECT ROW_NUMBER() OVER (ORDER BY SOURCE_KEY NULLS FIRST, DIABETES_COHORT_DEFINITION NULLS FIRST) AS SOURCE_ID, SOURCE_KEY, DIABETES_COHORT_DEFINITION
FROM (SELECT DISTINCT SOURCE_KEY, DIABETES_COHORT_DEFINITION FROM ETL_ENCOUNTER_TYPED)
WHERE NOT EXISTS (SELECT 1 FROM DIM_SOURCE);

CREATE TABLE IF NOT EXISTS DIM_PERIOD (
    PERIOD_ID NUMBER(38,0) NOT NULL PRIMARY KEY,
    PERIOD VARCHAR,
    DISCHARGE_YEAR NUMBER(38,0)
);

INSERT INTO DIM_PERIOD
SELECT ROW_NUMBER() OVER (ORDER BY PERIOD NULLS FIRST, DISCHARGE_YEAR NULLS FIRST) AS PERIOD_ID, PERIOD, DISCHARGE_YEAR
FROM (SELECT DISTINCT PERIOD, DISCHARGE_YEAR FROM ETL_ENCOUNTER_TYPED)
WHERE NOT EXISTS (SELECT 1 FROM DIM_PERIOD);

CREATE TABLE IF NOT EXISTS DIM_DEMOGRAPHIC (
    DEMOGRAPHIC_ID NUMBER(38,0) NOT NULL PRIMARY KEY,
    SOURCE_KEY VARCHAR,
    AGE_BAND_RAW VARCHAR,
    AGE_BAND_COMMON VARCHAR,
    GENDER VARCHAR,
    RACE_RAW VARCHAR,
    ETHNICITY_RAW VARCHAR
);

INSERT INTO DIM_DEMOGRAPHIC
SELECT ROW_NUMBER() OVER (ORDER BY SOURCE_KEY NULLS FIRST, AGE_BAND_RAW NULLS FIRST, AGE_BAND_COMMON NULLS FIRST, GENDER NULLS FIRST, RACE_RAW NULLS FIRST, ETHNICITY_RAW NULLS FIRST) AS DEMOGRAPHIC_ID, SOURCE_KEY, AGE_BAND_RAW, AGE_BAND_COMMON, GENDER, RACE_RAW, ETHNICITY_RAW
FROM (SELECT DISTINCT SOURCE_KEY, AGE_BAND_RAW, AGE_BAND_COMMON, GENDER, RACE_RAW, ETHNICITY_RAW FROM ETL_ENCOUNTER_TYPED)
WHERE NOT EXISTS (SELECT 1 FROM DIM_DEMOGRAPHIC);

CREATE TABLE IF NOT EXISTS DIM_ADMISSION (
