SELECT 'Invalid typed source values' AS CHECK_NAME, (SELECT COUNT(*) FROM STAGING.MODELLED_RAW r JOIN ETL_ENCOUNTER_TYPED t ON r.ENCOUNTER_KEY=t.ENCOUNTER_KEY WHERE (r.DISCHARGE_YEAR IS NOT NULL AND t.DISCHARGE_YEAR IS NULL) OR (r.LOS_DAYS_LOWER_BOUND IS NOT NULL AND t.LOS_DAYS_LOWER_BOUND IS NULL) OR (r.LOS_TOP_CODED IS NOT NULL AND t.LOS_TOP_CODED IS NULL) OR (r.TOTAL_CHARGES_USD IS NOT NULL AND t.TOTAL_CHARGES_USD IS NULL) OR (r.TOTAL_COSTS_USD IS NOT NULL AND t.TOTAL_COSTS_USD IS NULL) OR (r.SEVERITY_CODE IS NOT NULL AND t.SEVERITY_CODE IS NULL) OR (r.READMISSION_LABEL_AVAILABLE IS NOT NULL AND t.READMISSION_LABEL_AVAILABLE IS NULL) OR (r.IS_SYNTHETIC IS NOT NULL AND t.IS_SYNTHETIC IS NULL) OR (r.UCI_NUM_LAB_PROCEDURES IS NOT NULL AND t.UCI_NUM_LAB_PROCEDURES IS NULL) OR (r.UCI_NUM_PROCEDURES IS NOT NULL AND t.UCI_NUM_PROCEDURES IS NULL) OR (r.UCI_NUM_MEDICATIONS IS NOT NULL AND t.UCI_NUM_MEDICATIONS IS NULL) OR (r.UCI_NUMBER_OUTPATIENT IS NOT NULL AND t.UCI_NUMBER_OUTPATIENT IS NULL) OR (r.UCI_NUMBER_EMERGENCY IS NOT NULL AND t.UCI_NUMBER_EMERGENCY IS NULL) OR (r.UCI_NUMBER_INPATIENT IS NOT NULL AND t.UCI_NUMBER_INPATIENT IS NULL) OR (r.UCI_NUMBER_DIAGNOSES IS NOT NULL AND t.UCI_NUMBER_DIAGNOSES IS NULL)) AS ACTUAL, 0 AS EXPECTED
);

SELECT * FROM V_WAREHOUSE_CHECKS ORDER BY STATUS, CHECK_NAME;

-- Final result must show PASS, 4,424,257 fact rows, 7 dimensions, and zero failed checks.
SELECT CASE WHEN (SELECT COUNT(*) FROM V_WAREHOUSE_CHECKS WHERE STATUS='FAIL')=0
       THEN 'PASS' ELSE 'FAIL' END AS WAREHOUSE_STATUS,
       (SELECT COUNT(*) FROM FACT_ENCOUNTER) AS FACT_ROWS,
       7 AS DIMENSION_TABLES,
       (SELECT COUNT(*) FROM V_WAREHOUSE_CHECKS WHERE STATUS='FAIL') AS FAILED_CHECKS;
