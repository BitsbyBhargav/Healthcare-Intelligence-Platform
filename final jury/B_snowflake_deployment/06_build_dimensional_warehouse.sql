CREATE TABLE IF NOT EXISTS FACT_ENCOUNTER (
    SOURCE_ID NUMBER(38,0) NOT NULL REFERENCES DIM_SOURCE(SOURCE_ID),
    PERIOD_ID NUMBER(38,0) NOT NULL REFERENCES DIM_PERIOD(PERIOD_ID),
    DEMOGRAPHIC_ID NUMBER(38,0) NOT NULL REFERENCES DIM_DEMOGRAPHIC(DEMOGRAPHIC_ID),
    ADMISSION_ID NUMBER(38,0) NOT NULL REFERENCES DIM_ADMISSION(ADMISSION_ID),
    DIAGNOSIS_ID NUMBER(38,0) NOT NULL REFERENCES DIM_DIAGNOSIS(DIAGNOSIS_ID),
    FACILITY_ID NUMBER(38,0) NOT NULL REFERENCES DIM_FACILITY(FACILITY_ID),
    TREATMENT_ID NUMBER(38,0) NOT NULL REFERENCES DIM_TREATMENT(TREATMENT_ID),
    ENCOUNTER_KEY VARCHAR NOT NULL PRIMARY KEY,
    SOURCE_ROW_ID VARCHAR,
    PATIENT_KEY VARCHAR,
    LOS_RAW VARCHAR,
    LOS_DAYS_LOWER_BOUND NUMBER(38,0),
    LOS_TOP_CODED BOOLEAN,
    TOTAL_CHARGES_USD NUMBER(18,2),
    TOTAL_COSTS_USD NUMBER(18,2),
    SEVERITY_CODE NUMBER(38,0),
    SEVERITY_DESCRIPTION VARCHAR,
    READMISSION_LABEL VARCHAR,
    READMISSION_LABEL_AVAILABLE BOOLEAN,
    IS_SYNTHETIC BOOLEAN,
    UCI_NUM_LAB_PROCEDURES NUMBER(38,0),
    UCI_NUM_PROCEDURES NUMBER(38,0),
    UCI_NUM_MEDICATIONS NUMBER(38,0),
    UCI_NUMBER_OUTPATIENT NUMBER(38,0),
    UCI_NUMBER_EMERGENCY NUMBER(38,0),
    UCI_NUMBER_INPATIENT NUMBER(38,0),
    UCI_NUMBER_DIAGNOSES NUMBER(38,0),
    UCI_DIAG_2 VARCHAR,
    UCI_DIAG_3 VARCHAR,
    MODEL_ROLE VARCHAR,
    LABEL_ORIGIN VARCHAR
);

INSERT INTO FACT_ENCOUNTER
SELECT d0.SOURCE_ID, d1.PERIOD_ID, d2.DEMOGRAPHIC_ID, d3.ADMISSION_ID, d4.DIAGNOSIS_ID, d5.FACILITY_ID, d6.TREATMENT_ID, s.ENCOUNTER_KEY, s.SOURCE_ROW_ID, s.PATIENT_KEY, s.LOS_RAW, s.LOS_DAYS_LOWER_BOUND, s.LOS_TOP_CODED, s.TOTAL_CHARGES_USD, s.TOTAL_COSTS_USD, s.SEVERITY_CODE, s.SEVERITY_DESCRIPTION, s.READMISSION_LABEL, s.READMISSION_LABEL_AVAILABLE, s.IS_SYNTHETIC, s.UCI_NUM_LAB_PROCEDURES, s.UCI_NUM_PROCEDURES, s.UCI_NUM_MEDICATIONS, s.UCI_NUMBER_OUTPATIENT, s.UCI_NUMBER_EMERGENCY, s.UCI_NUMBER_INPATIENT, s.UCI_NUMBER_DIAGNOSES, s.UCI_DIAG_2, s.UCI_DIAG_3, s.MODEL_ROLE, s.LABEL_ORIGIN
FROM ETL_ENCOUNTER_TYPED s
LEFT JOIN DIM_SOURCE d0 ON EQUAL_NULL(s.SOURCE_KEY,d0.SOURCE_KEY) AND EQUAL_NULL(s.DIABETES_COHORT_DEFINITION,d0.DIABETES_COHORT_DEFINITION)
LEFT JOIN DIM_PERIOD d1 ON EQUAL_NULL(s.PERIOD,d1.PERIOD) AND EQUAL_NULL(s.DISCHARGE_YEAR,d1.DISCHARGE_YEAR)
LEFT JOIN DIM_DEMOGRAPHIC d2 ON EQUAL_NULL(s.SOURCE_KEY,d2.SOURCE_KEY) AND EQUAL_NULL(s.AGE_BAND_RAW,d2.AGE_BAND_RAW) AND EQUAL_NULL(s.AGE_BAND_COMMON,d2.AGE_BAND_COMMON) AND EQUAL_NULL(s.GENDER,d2.GENDER) AND EQUAL_NULL(s.RACE_RAW,d2.RACE_RAW) AND EQUAL_NULL(s.ETHNICITY_RAW,d2.ETHNICITY_RAW)
LEFT JOIN DIM_ADMISSION d3 ON EQUAL_NULL(s.SOURCE_KEY,d3.SOURCE_KEY) AND EQUAL_NULL(s.ADMISSION_TYPE_RAW,d3.ADMISSION_TYPE_RAW) AND EQUAL_NULL(s.ADMISSION_TYPE_COMMON,d3.ADMISSION_TYPE_COMMON) AND EQUAL_NULL(s.DISPOSITION_RAW,d3.DISPOSITION_RAW) AND EQUAL_NULL(s.PAYMENT_TYPE,d3.PAYMENT_TYPE) AND EQUAL_NULL(s.UCI_ADMISSION_SOURCE_ID,d3.UCI_ADMISSION_SOURCE_ID)
LEFT JOIN DIM_DIAGNOSIS d4 ON EQUAL_NULL(s.SOURCE_KEY,d4.SOURCE_KEY) AND EQUAL_NULL(s.DIAGNOSIS_SYSTEM,d4.DIAGNOSIS_SYSTEM) AND EQUAL_NULL(s.DIAGNOSIS_CODE,d4.DIAGNOSIS_CODE) AND EQUAL_NULL(s.DIAGNOSIS_DESCRIPTION,d4.DIAGNOSIS_DESCRIPTION) AND EQUAL_NULL(s.APR_DRG_CODE,d4.APR_DRG_CODE)
LEFT JOIN DIM_FACILITY d5 ON EQUAL_NULL(s.SOURCE_KEY,d5.SOURCE_KEY) AND EQUAL_NULL(s.FACILITY_KEY,d5.FACILITY_KEY) AND EQUAL_NULL(s.FACILITY_NAME,d5.FACILITY_NAME) AND EQUAL_NULL(s.HOSPITAL_COUNTY,d5.HOSPITAL_COUNTY) AND EQUAL_NULL(s.SERVICE_AREA,d5.SERVICE_AREA)
LEFT JOIN DIM_TREATMENT d6 ON EQUAL_NULL(s.SOURCE_KEY,d6.SOURCE_KEY) AND EQUAL_NULL(s.UCI_INSULIN,d6.UCI_INSULIN) AND EQUAL_NULL(s.UCI_CHANGE,d6.UCI_CHANGE) AND EQUAL_NULL(s.UCI_DIABETESMED,d6.UCI_DIABETESMED) AND EQUAL_NULL(s.UCI_A1CRESULT,d6.UCI_A1CRESULT) AND EQUAL_NULL(s.UCI_MAX_GLU_SERUM,d6.UCI_MAX_GLU_SERUM)
WHERE NOT EXISTS (SELECT 1 FROM FACT_ENCOUNTER);

