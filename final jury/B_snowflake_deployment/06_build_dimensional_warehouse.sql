INSERT INTO DIM_DIAGNOSIS
SELECT ROW_NUMBER() OVER (ORDER BY SOURCE_KEY NULLS FIRST, DIAGNOSIS_SYSTEM NULLS FIRST, DIAGNOSIS_CODE NULLS FIRST, DIAGNOSIS_DESCRIPTION NULLS FIRST, APR_DRG_CODE NULLS FIRST) AS DIAGNOSIS_ID, SOURCE_KEY, DIAGNOSIS_SYSTEM, DIAGNOSIS_CODE, DIAGNOSIS_DESCRIPTION, APR_DRG_CODE
